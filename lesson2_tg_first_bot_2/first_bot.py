import telebot  # Подключаем библиотеку для работы с Telegram-ботом.
import random  # Подключаем библиотеку для генерации случайных чисел.

bot = telebot.TeleBot(  # Начинаем создавать объект Telegram-бота.
    "8852272774:AAHz9_bqWjUTpDWB80HuzK8nSpMNsQy5c4M"  # Передаем токен бота.
)  # Создаем объект бота по токену.

user_number = 0  # Здесь будет храниться число, которое ввел пользователь.
comp_number = 0  # Здесь будет храниться число, которое загадал компьютер.

left_side = 0  # Здесь будет храниться левая граница текущего диапазона.
right_side = 0  # Здесь будет храниться правая граница текущего диапазона.

count_tries = 0  # Здесь будет храниться количество попыток пользователя.

HAPPY_NUMBER = 777  # Это секретное число для показа правильного ответа.


@bot.message_handler(  # Начинаем описывать обработчик сообщений.
    func=lambda message: True  # Говорим обработчику принимать любое сообщение.
)  # Этот обработчик принимает любые сообщения.
def process_all_text_messages(message):  # Функция запускается при получении сообщения.
    global user_number  # Разрешаем менять глобальную переменную user_number.
    global comp_number  # Разрешаем менять глобальную переменную comp_number.
    global left_side  # Разрешаем менять глобальную переменную left_side.
    global right_side  # Разрешаем менять глобальную переменную right_side.
    global count_tries  # Разрешаем менять глобальную переменную count_tries.

    input_text = (  # Начинаем сохранять обработанный текст пользователя.
        message.text.lower()  # Получаем текст сообщения маленькими буквами.
    )  # Берем текст сообщения и переводим его в нижний регистр.

    output_text = ""  # Создаем пустую строку для будущего ответа бота.

    if input_text == "/start":  # Проверяем, написал ли пользователь команду старта.
        left_side = 1  # Устанавливаем левую границу диапазона.
        right_side = 100  # Устанавливаем правую границу диапазона.

        count_tries = 0  # Обнуляем счетчик попыток для новой игры.

        comp_number = random.randint(  # Начинаем загадывать случайное число.
            left_side, right_side  # Указываем границы для случайного числа.
        )  # Загадываем случайное число от 1 до 100.
        user_number = 0  # Сбрасываем число пользователя перед новой игрой.

        output_text = f"я загадал число от {left_side} до {right_side}. попробуй отгадай. введи число, котороя я загадал"  # Готовим ответ с правилами игры.
    else:  # Если это не команда /start, считаем сообщение попыткой угадать число.
        user_number = int(input_text)  # Превращаем текст пользователя в целое число.

        count_tries += 1  # Увеличиваем счетчик попыток на один.

        if user_number == HAPPY_NUMBER:  # Проверяем, ввел ли пользователь секретное число.
            output_text = f"Вы нашли секретное число. Правильный ответ {comp_number}"  # Показываем загаданное число.
            count_tries -= 1  # Не считаем секретное число обычной попыткой.
        elif (  # Иначе проверяем, меньше ли число пользователя.
            user_number < comp_number  # Сравниваем число пользователя с загаданным.
        ):  # Проверяем, меньше ли число пользователя загаданного.
            left_side = user_number  # Сдвигаем левую границу к числу пользователя.
            output_text = f"введи побольше, текущий отрезок от {left_side} до {right_side}"  # Просим ввести число больше.
        elif (  # Иначе проверяем, больше ли число пользователя.
            user_number > comp_number  # Сравниваем число пользователя с загаданным.
        ):  # Проверяем, больше ли число пользователя загаданного.
            right_side = user_number  # Сдвигаем правую границу к числу пользователя.
            output_text = f"введи поменьше, текущий отрезок от {left_side} до {right_side}"  # Просим ввести число меньше.
        elif user_number == comp_number:  # Проверяем, угадал ли пользователь число.
            output_text = f"урааа! ты угадал.\n\nзатрачено попыток: {count_tries}\n\nдля новой игры введи /start"  # Сообщаем о победе.

    bot.send_message(  # Начинаем отправлять сообщение пользователю.
        message.chat.id, output_text  # Передаем id чата и текст ответа.
    )  # Отправляем подготовленный ответ в тот же чат.


bot.infinity_polling()  # Постоянно запускаем проверку новых сообщений.
